/// Apply keyword case transformation to a SQL string.
///
/// Preserves quoted identifiers and string literals.
/// Copy the rest of a single-quoted literal (opening quote already emitted)
/// into `result`, honoring `''` (SQL escaped-quote) the same way
/// `split::scan_single_quoted` does — a lone `'` closes the literal.
pub(in crate::formatter) fn copy_single_quoted(
    chars: &mut std::iter::Peekable<std::str::Chars<'_>>,
    result: &mut String,
) {
    while let Some(ch) = chars.next() {
        result.push(ch);
        if ch == '\'' {
            // `''` escape stays inside the string; a lone `'` closes it.
            if chars.peek() == Some(&'\'') {
                result.push(chars.next().unwrap());
                continue;
            }
            break;
        }
    }
}

/// Copy the rest of a double-quoted identifier (opening quote already emitted).
pub(in crate::formatter) fn copy_quoted_ident(
    chars: &mut std::iter::Peekable<std::str::Chars<'_>>,
    result: &mut String,
) {
    for ch in chars.by_ref() {
        result.push(ch);
        if ch == '"' {
            break;
        }
    }
}

/// Copy the rest of a `$$ … $$` body (opening `$$` already emitted).
pub(in crate::formatter) fn copy_dollar_body(
    chars: &mut std::iter::Peekable<std::str::Chars<'_>>,
    result: &mut String,
) {
    loop {
        match chars.next() {
            Some('$') if chars.peek() == Some(&'$') => {
                result.push('$');
                result.push(chars.next().unwrap());
                break;
            }
            Some(ch) => result.push(ch),
            None => break,
        }
    }
}

/// Read an identifier-like word beginning with `first`, consuming trailing
/// alphanumeric/underscore characters from `chars`.
pub(in crate::formatter) fn read_word(first: char, chars: &mut std::iter::Peekable<std::str::Chars<'_>>) -> String {
    let mut word = String::new();
    word.push(first);
    while let Some(&next) = chars.peek() {
        if next.is_ascii_alphanumeric() || next == '_' {
            word.push(chars.next().unwrap());
        } else {
            break;
        }
    }
    word
}

/// Re-case `word` per `case` when it is a SQL keyword; otherwise return it as-is.
pub(in crate::formatter) fn recase_keyword(word: &str, keywords: &HashSet<&'static str>, case: &KeywordCase) -> String {
    if !keywords.contains(word.to_uppercase().as_str()) {
        return word.to_string();
    }
    match case {
        KeywordCase::Lower => word.to_lowercase(),
        KeywordCase::Upper => word.to_uppercase(),
        KeywordCase::Preserve => word.to_string(),
    }
}

pub(in crate::formatter) fn apply_keyword_case(sql: &str, case: &KeywordCase) -> String {
    if matches!(case, KeywordCase::Preserve) {
        return sql.to_string();
    }

    let keywords = sql_keywords();
    let mut result = String::with_capacity(sql.len());
    let mut chars = sql.chars().peekable();

    while let Some(c) = chars.next() {
        // Skip string literals (single quotes)
        if c == '\'' {
            result.push(c);
            copy_single_quoted(&mut chars, &mut result);
            continue;
        }

        // Skip quoted identifiers (double quotes)
        if c == '"' {
            result.push(c);
            copy_quoted_ident(&mut chars, &mut result);
            continue;
        }

        // Skip $$ quoted bodies (format_dollar_quoted normally handles these
        // for function bodies, so we shouldn't usually reach here).
        if c == '$' && chars.peek() == Some(&'$') {
            result.push(c);
            result.push(chars.next().unwrap());
            copy_dollar_body(&mut chars, &mut result);
            continue;
        }

        // Collect a word and re-case it when it is a keyword.
        if c.is_ascii_alphabetic() || c == '_' {
            let word = read_word(c, &mut chars);
            result.push_str(&recase_keyword(&word, &keywords, case));
            continue;
        }

        result.push(c);
    }

    result
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Every clause dbd's own emitter writes — what `init --from-db` hands the
    /// formatter — and the built-in types DDL is written with recase as one.
    /// Missing from the list, `GENERATED`, `IDENTITY`, `RESTRICT` and `VALID`
    /// kept their case while their neighbours lost it: `GENERATED by default
    /// as IDENTITY`, `on delete RESTRICT`.
    #[test]
    fn every_keyword_the_emitter_writes_recases_with_its_neighbours() {
        // Identifiers are lowercase, so everything uppercase here is a keyword
        // or a built-in type.
        let sql = "CREATE TABLE IF NOT EXISTS t ( \
            a BIGINT GENERATED ALWAYS AS IDENTITY, \
            b BIGINT GENERATED BY DEFAULT AS IDENTITY, \
            c NUMERIC(10, 2) GENERATED ALWAYS AS (a + 1) STORED, \
            d BYTEA, e TIMESTAMPTZ, f TIMETZ, g JSONB, h JSON, i INET, j CIDR, k MONEY, \
            l BOOL, m INT2, n INT4, o INT8, p FLOAT4, q FLOAT8, \
            FOREIGN KEY (a) REFERENCES u (a) MATCH FULL ON DELETE RESTRICT ON UPDATE NO ACTION, \
            FOREIGN KEY (b) REFERENCES u (b) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED, \
            UNIQUE NULLS NOT DISTINCT (c), \
            CONSTRAINT x CHECK (a > 0) NOT VALID \
            ); \
            CREATE MATERIALIZED VIEW IF NOT EXISTS v AS SELECT a FROM t WITH DATA; \
            CREATE UNIQUE INDEX IF NOT EXISTS ix ON t USING GIN (g); \
            COMMENT ON MATERIALIZED VIEW v IS 'Kept As Written';";

        let lowered = apply_keyword_case(sql, &KeywordCase::Lower);

        let expected = sql.to_lowercase().replace("'kept as written'", "'Kept As Written'");
        assert_eq!(lowered, expected);
    }
}
